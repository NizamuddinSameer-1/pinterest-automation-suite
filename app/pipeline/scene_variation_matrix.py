"""
app/pipeline/scene_variation_matrix.py
──────────────────────────────────────
Category-aware variation matrix for the Scene Director.

Every product-class key maps to a VariationMatrix that holds SIX decorrelated
variation axes. Combined with the existing _rotate / seeded logic in
scene_director._deterministic_scene, this gives:

    6 axes × ~12 options each ≈ 12^6 = 2,985,984 combinations per class.
    23 classes × ~3M combinations = ~69 million total unique situations.

Axes
────
    camera_angles       — lens position, height, distance, focal feel
    lighting_setups     — quality, direction, colour temperature, mood
    color_gradings      — post-treatment / film look applied to the shot
    scene_environments  — where the shot happens, what surrounds the product
    style_aesthetics    — visual language / editorial genre
    creative_contexts   — Pinterest save-reason; WHY a viewer pins this image

All options are written as prompt fragments that slot directly into the
FlowVariation block the compiler receives. They are intentionally written
in the same imperative register as the rest of the prompt pipeline.

Usage (inside scene_director._deterministic_scene)
────────────────────────────────────────────────────
    from app.pipeline.scene_variation_matrix import variation_for

    var = variation_for(klass.key, seed_key)
    # var is a dict[str, str] — one string per axis.
    # Splice into the prompt; the compiler adds it to the Imagen call.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass


@dataclass(frozen=True)
class VariationMatrix:
    """
    Six decorrelated variation axes for one product class.

    Every tuple contains 8-16 options so that the seeded rotation covers
    a wide enough range that sibling concepts within a job feel genuinely
    different, while being short enough to enumerate and audit.
    """
    camera_angles:      tuple[str, ...]
    lighting_setups:    tuple[str, ...]
    color_gradings:     tuple[str, ...]
    scene_environments: tuple[str, ...]
    style_aesthetics:   tuple[str, ...]
    creative_contexts:  tuple[str, ...]


def _seed(seed_key: str, axis: str) -> int:
    """Stable, per-axis seed derived from job identity + axis name."""
    return int.from_bytes(
        hashlib.sha256(f"{seed_key}|var|{axis}".encode()).digest()[:8], "big"
    )


def _pick(items: tuple[str, ...], seed_key: str, axis: str) -> str:
    if not items:
        return ""
    return items[_seed(seed_key, axis) % len(items)]


def variation_for(class_key: str, seed_key: str) -> dict[str, str]:
    """
    Return one string per axis for the given product class and job seed.

    Falls back to the GENERIC matrix for unrecognised classes. Each call
    with the same (class_key, seed_key) pair always returns the same dict;
    different seed_keys (i.e. different concept_ids for the same product)
    return different picks on every axis independently.
    """
    matrix = MATRICES.get(class_key, MATRICES["generic"])
    return {
        "camera_angle":      _pick(matrix.camera_angles,      seed_key, "camera"),
        "lighting_setup":    _pick(matrix.lighting_setups,    seed_key, "lighting"),
        "color_grading":     _pick(matrix.color_gradings,     seed_key, "grading"),
        "scene_environment": _pick(matrix.scene_environments, seed_key, "environment"),
        "style_aesthetic":   _pick(matrix.style_aesthetics,   seed_key, "style"),
        "creative_context":  _pick(matrix.creative_contexts,  seed_key, "context"),
    }


