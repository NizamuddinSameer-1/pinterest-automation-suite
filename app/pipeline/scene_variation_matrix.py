# ── Public API ────────────────────────────────────────────────────────────

def list_supported_classes() -> list[str]:
    """All product-class keys that have a dedicated VariationMatrix."""
    return sorted(MATRICES.keys())


def axis_options(class_key: str, axis: str) -> tuple[str, ...]:
    """
    Return all options for one axis and one class key.
    Useful for testing and auditing coverage.
    """
    matrix = MATRICES.get(class_key, MATRICES["generic"])
    return getattr(matrix, axis, ())
